# ==============================================================================
# Data Structures
# ==============================================================================


@dataclass
class MLPerfEntry:
    platform: str
    accelerator: str
    process_node: str
    mlperf_division: str  # Training or Inference
    mlperf_round: str  # e.g., Training v0.5, Inference v4.1
    round_date: str  # YYYY-MM
    months_since_platform_debut: int
    benchmark_workload: str
    system_scale: str
    raw_result: float
    raw_unit: str
    metric_type: str  # Time-to-Train (lower better) or Throughput (higher better)
    normalized_in_place_dividend: float
    generational_leap_multiplier: str
    software_stack_version: str
    primary_optimizations: str
    submission_id: str
    result_url: str


@dataclass
class KernelFragmentationEntry:
    engine: str
    version_tag: str
    release_date: str
    git_commit: str
    github_repo_url: str
    total_repo_loc: int
    total_custom_kernel_loc: int
    attention_kernel_loc: int
    quantization_kernel_loc: int
    moe_dispatch_kernel_loc: int
    collective_comm_kernel_loc: int
    backend_arch_loc: int
    python_orchestration_loc: int
    custom_kernel_loc_growth_factor: float
    kernel_technologies: str
    primary_architectural_drivers: str


