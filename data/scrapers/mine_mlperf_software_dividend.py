def validate_data(
    mlperf_entries: list[MLPerfEntry], kernel_entries: list[KernelFragmentationEntry]
) -> None:
    """Validates structural and numeric integrity of datasets."""
    # Check MLPerf invariants
    for e in mlperf_entries:
        assert (
            e.normalized_in_place_dividend >= 1.0
        ), f"Dividend must be >= 1.0: {e.platform} ({e.mlperf_round})"
        assert (
            e.months_since_platform_debut >= 0
        ), f"Months must be non-negative: {e.platform}"
        assert e.raw_result > 0, f"Raw result must be positive: {e.platform}"

    # Check Kernel fragmentation invariants
    for k in kernel_entries:
        assert (
            k.total_repo_loc > 0
        ), f"Total LOC must be positive: {k.engine} {k.version_tag}"
        assert (
            k.total_custom_kernel_loc > 0
        ), f"Kernel LOC must be positive: {k.engine} {k.version_tag}"
        assert (
            k.custom_kernel_loc_growth_factor >= 1.0
        ), f"Growth factor must be >= 1.0: {k.engine}"
        assert (
            k.attention_kernel_loc
            + k.quantization_kernel_loc
            + k.moe_dispatch_kernel_loc
            + k.collective_comm_kernel_loc
            + k.backend_arch_loc
            <= k.total_custom_kernel_loc
        ), f"Kernel breakdown cannot exceed total custom kernel LOC: {k.engine} {k.version_tag}"

    print("  [OK] All dataset invariants passed validation.")


def main() -> None:
    print("Mining MLPerf Software Dividend and LLM Inference Kernel Proliferation...")
    mlperf_entries = get_mlperf_longitudinal_dataset()
    kernel_entries = get_inference_kernel_fragmentation_dataset()

    validate_data(mlperf_entries, kernel_entries)

    out_mlperf = RECEIPTS_DIR / "mlperf_longitudinal_software_dividend.csv"
    out_kernel = RECEIPTS_DIR / "inference_kernel_fragmentation.csv"

    write_mlperf_receipt(mlperf_entries, out_mlperf)
    write_kernel_fragmentation_receipt(kernel_entries, out_kernel)
    print("Done mining and generating receipts.")


if __name__ == "__main__":
    main()
