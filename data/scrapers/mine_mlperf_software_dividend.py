#!/usr/bin/env python3
"""
Longitudinal MLPerf Software Dividend & Inference Kernel Fragmentation Scraper / Miner
======================================================================================
Tracks two co-evolving empirical phenomena in AI systems (2018–2026):

1. The Longitudinal MLPerf Software Dividend (MLCommons Benchmarks):
   Quantifies the in-place throughput gains achieved on frozen physical silicon
   solely through algorithmic, compiler, kernel, and systems software maturation
   (1.5x - 3.8x speedups on identical hardware over 12-36 months) vs. generational
   hardware step-functions (2.0x - 8.0x silicon debut jumps).

2. The Software Porting Wall & Custom Kernel Fragmentation:
   Analyzes leading production LLM inference serving runtimes (vLLM, TensorRT-LLM,
   SGLang, TGI) across 2023-2026, measuring the explosive proliferation of bespoke
   hand-written C++/CUDA/Triton/CUTLASS kernels (attention, quantization, MoE dispatch,
   custom communication, and architecture-specific inline PTX/assembly).

Outputs:
  - data/source-receipts/mlperf_longitudinal_software_dividend.csv
  - data/source-receipts/inference_kernel_fragmentation.csv
"""

