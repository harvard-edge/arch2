def write_mlperf_receipt(entries: list[MLPerfEntry], output_path: Path) -> None:
    """Writes the longitudinal MLPerf software dividend dataset with provenance header."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    header_comment = """# MLCommons MLPerf Datacenter Benchmark Longitudinal Software Dividend (2018-2026)
# Sources: Official MLCommons Training (v0.5-v5.1) and Inference (v1.0-v6.0) peer-reviewed benchmark results.
# Provenance: https://mlcommons.org/benchmarks/training/ and https://mlcommons.org/benchmarks/inference/
# Methodology: Traces identical physical hardware configurations over time to quantify in-place software throughput maturation (1.5x-3.8x) vs generational silicon steps (2.0x-8.0x).
# Generated by: data/scrapers/mine_mlperf_software_dividend.py
"""
    fieldnames = [
        "platform",
        "accelerator",
        "process_node",
        "mlperf_division",
        "mlperf_round",
        "round_date",
        "months_since_platform_debut",
        "benchmark_workload",
        "system_scale",
        "raw_result",
        "raw_unit",
        "metric_type",
        "normalized_in_place_dividend",
        "generational_leap_multiplier",
        "software_stack_version",
        "primary_optimizations",
        "submission_id",
        "result_url",
    ]

    with open(output_path, "w", newline="", encoding="utf-8") as f:
        f.write(header_comment)
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for entry in entries:
            writer.writerow(asdict(entry))

    print(
        f"  [OK] Wrote MLPerf dividend receipt ({len(entries)} rows) -> {output_path}"
    )


